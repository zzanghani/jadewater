// 전 직급 공통 커트라인. 4개 분기 돌린 뒤 실제 분포를 보고 한 번 재검토한다.
export function evalGrade(total: number): { grade: EvalGrade; label: string } {
  if (total >= 90) return { grade: "S", label: "핵심인재" };
  if (total >= 80) return { grade: "A", label: "우수성과" };
  if (total >= 70) return { grade: "B", label: "표준 수행" };
  if (total >= 55) return { grade: "C", label: "개선 필요" };
  return { grade: "D", label: "재검토" };
}

// 직급별 등급 조치. 수습은 전환 판정, 나머지는 연봉·성과급.
export function gradeAction(grade: EvalGrade, probation: boolean, position: ScheduleRole): string {
  if (probation) {
    if (grade === "S" || grade === "A") return "정직원 전환";
    if (grade === "B") return "수습 1개월 연장 후 재평가";
    if (grade === "C") return "전환 보류 · 내부 검토";
    return "부적격";
  }
  const bonus = position === "부점장" ? "분기 성과급 + " : "";
  if (grade === "S") return `${bonus}연봉 +6%`;
  if (grade === "A") return `${bonus}연봉 +4%`;
  if (grade === "B") return "연봉 +2%";
  if (grade === "C") return position === "부점장" ? "동결 + 90일 개선계획" : "동결 + 개선 면담";
  return position === "부점장" ? "보직 재검토" : "재계약 재검토";
}
