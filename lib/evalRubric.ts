// 입사 3개월 이내면 수습으로 본다. 명부에 수습 구분이 따로 없어서
// 입사일로 판단한다 — 나중에 구분 칸이 생기면 그걸 우선한다.
export function isProbation(hireDate: string, asOf = new Date()): boolean {
  const hired = new Date(`${hireDate}T00:00:00+09:00`);
  const months =
    (asOf.getFullYear() - hired.getFullYear()) * 12 + (asOf.getMonth() - hired.getMonth());
  return months < 3;
}

export function rubricFor(
  position: ScheduleRole,
  team: EmployeeTeam | null,
  probation: boolean
): EvalRubric | null {
  if (position === "점장") return null; // 점장은 자동 지표 기반 별도 체계
  if (position === "파트타이머") return null; // 파트타이머는 앱을 쓰지 않는다
  if (position === "부점장") return DEPUTY;
  if (position === "팀장") return LEADER;
  if (probation) return team === "키친" ? PROBATION_KITCHEN : PROBATION_HALL;
  return team === "키친" ? REGULAR_KITCHEN : REGULAR_HALL;
}

// 카테고리별 평균(1~5)을 가중치에 비례 배분해 100점으로 환산한다.
// 안 찍은 문항이 있으면 그 문항은 평균에서 빼고 계산한다.
export function scoreRubric(
  rubric: EvalRubric,
  scores: Record<string, number>
): { total: number; byCategory: { name: string; score: number; weight: number }[] } {
  const byCategory = rubric.categories.map((cat) => {
    const items = rubric.items.filter((i) => i.category === cat.name);
    const values = items.map((i) => scores[i.id]).filter((v): v is number => typeof v === "number");
    const avg = values.length ? values.reduce((a, b) => a + b, 0) / values.length : 0;
    return { name: cat.name, score: Math.round((avg / 5) * cat.weight * 10) / 10, weight: cat.weight };
  });
  const total = Math.round(byCategory.reduce((sum, c) => sum + c.score, 0));
  return { total, byCategory };
}

export type EvalGrade = "S" | "A" | "B" | "C" | "D";

